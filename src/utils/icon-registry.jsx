// Back-compat alias + dynamic (by string name) lookup.
export const iconRegistry = CippIcons
export const getIconComponentByName = (iconName) => CippIcons[iconName] ?? null
export const getIconByName = (iconName, props = {}) => {
  const Icon = getIconComponentByName(iconName)
  return Icon ? <Icon {...props} /> : null
}

